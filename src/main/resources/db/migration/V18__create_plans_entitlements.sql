CREATE TABLE plans (
    id UUID PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL,
    active BOOLEAN NOT NULL,
    price_cents INTEGER,
    currency VARCHAR(3) NOT NULL DEFAULT 'BRL',
    billing_period VARCHAR(30),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_plans_code CHECK (code IN ('FREE','PREMIUM')),
    CONSTRAINT chk_plans_price CHECK (price_cents IS NULL OR price_cents >= 0),
    CONSTRAINT chk_plans_currency CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE TABLE plan_features (
    id UUID PRIMARY KEY,
    plan_id UUID NOT NULL,
    feature_code VARCHAR(80) NOT NULL,
    enabled BOOLEAN NOT NULL,
    limit_value INTEGER,
    CONSTRAINT fk_plan_features_plan FOREIGN KEY (plan_id) REFERENCES plans (id) ON DELETE CASCADE,
    CONSTRAINT uq_plan_features_plan_code UNIQUE (plan_id, feature_code),
    CONSTRAINT chk_plan_features_code CHECK (feature_code IN (
        'MAX_ATS_CAREERS','MAX_ETS2_CAREERS','BATCH_EXPORT','XLSX_EXPORT','FULL_HISTORY','ADVANCED_CHARTS'
    )),
    CONSTRAINT chk_plan_features_limit CHECK (limit_value IS NULL OR limit_value >= 0)
);

CREATE TABLE subscriptions (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    plan_id UUID NOT NULL,
    status VARCHAR(30) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    current_period_start TIMESTAMP WITH TIME ZONE,
    current_period_end TIMESTAMP WITH TIME ZONE,
    cancel_at_period_end BOOLEAN NOT NULL DEFAULT FALSE,
    canceled_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_subscriptions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_subscriptions_plan FOREIGN KEY (plan_id) REFERENCES plans (id),
    CONSTRAINT chk_subscriptions_status CHECK (status IN ('PENDING_PAYMENT','ACTIVE','PAST_DUE','CANCELED','EXPIRED')),
    CONSTRAINT chk_subscriptions_period CHECK (
        current_period_start IS NULL OR current_period_end IS NULL OR current_period_end > current_period_start
    )
);

CREATE INDEX idx_plan_features_plan ON plan_features (plan_id, feature_code);
CREATE INDEX idx_subscriptions_user_status ON subscriptions (user_id, status, updated_at DESC, id DESC);
CREATE UNIQUE INDEX uq_subscriptions_user_open
    ON subscriptions (user_id)
    WHERE status IN ('PENDING_PAYMENT','ACTIVE','PAST_DUE');

